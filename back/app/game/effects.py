    @property
    def triggers(self) -> list[EffectTrigger]:
        return [EffectTrigger.PASSIVE]
    
    def execute(self, context: EffectContext) -> EffectResult:
        return EffectResult(
            state_modifications=[
                f"Contribute +{self.bonus_amount} {self.element_id} element"
            ]
        )


