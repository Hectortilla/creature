class OnPlayEffect(Effect):
    """
    Effect that triggers when a card enters play.
    """
    
    def __init__(self, effect_id: str, name: str, description: str = "",
                 draw_cards: int = 0, damage_to_enemy: int = 0):
        super().__init__(effect_id, name, description)
        self.draw_cards = draw_cards
        self.damage_to_enemy = damage_to_enemy
    
    @property
    def triggers(self) -> list[EffectTrigger]:
        return [EffectTrigger.ON_PLAY]
    
    def should_trigger(self, context: EffectContext) -> bool:
        if not super().should_trigger(context):
            return False
        # Check if the triggering event is for this card
        if isinstance(context.trigger_event, CardPlayedEvent):
            return context.trigger_event.card_id == context.source_card.instance_id
        return False
    
    def execute(self, context: EffectContext) -> EffectResult:
        events = []
        modifications = []
        
        if self.draw_cards > 0:
            # Drawing is handled by the engine
            modifications.append(f"Draw {self.draw_cards} cards")
        
        if self.damage_to_enemy > 0:
            modifications.append(f"Deal {self.damage_to_enemy} damage to enemy")
        
        return EffectResult(events=events, state_modifications=modifications)


class OnDestroyEffect(Effect):
    """
    Effect that triggers when a card is destroyed.
    """
    
    def __init__(self, effect_id: str, name: str, description: str = "",
                 return_to_hand: bool = False, deal_damage: int = 0,
                 target_attacker: bool = False):
        super().__init__(effect_id, name, description)
        self.return_to_hand = return_to_hand
        self.deal_damage = deal_damage
        self.target_attacker = target_attacker
    
    @property
    def triggers(self) -> list[EffectTrigger]:
        return [EffectTrigger.ON_DESTROY]
    
    def should_trigger(self, context: EffectContext) -> bool:
        if isinstance(context.trigger_event, CardDestroyedEvent):
            return context.trigger_event.card_id == context.source_card.instance_id
        return False
    
    def execute(self, context: EffectContext) -> EffectResult:
        modifications = []
        
        if self.return_to_hand:
            modifications.append("Return to hand instead of graveyard")
        
        if self.deal_damage > 0:
            target = "attacker" if self.target_attacker else "random enemy"
            modifications.append(f"Deal {self.deal_damage} damage to {target}")
        
        return EffectResult(state_modifications=modifications)


class OnAttackEffect(Effect):
    """
    Effect that triggers when this card attacks.
    """
    
    def __init__(self, effect_id: str, name: str, description: str = "",
                 bonus_damage: int = 0, lifesteal: bool = False,
                 attack_twice: bool = False):
        super().__init__(effect_id, name, description)
        self.bonus_damage = bonus_damage
        self.lifesteal = lifesteal
        self.attack_twice = attack_twice
    
    @property
    def triggers(self) -> list[EffectTrigger]:
        return [EffectTrigger.ON_ATTACK]
    
    def should_trigger(self, context: EffectContext) -> bool:
        if isinstance(context.trigger_event, AttackDeclaredEvent):
            return context.trigger_event.attacker_id == context.source_card.instance_id
        return False
    
    def execute(self, context: EffectContext) -> EffectResult:
        modifications = []
        
        if self.bonus_damage > 0:
            modifications.append(f"+{self.bonus_damage} bonus damage")
        
        if self.lifesteal:
            modifications.append("Heal for damage dealt")
        
        if self.attack_twice:
            modifications.append("Attack again")
        
        return EffectResult(state_modifications=modifications)


